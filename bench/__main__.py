"""``python -m bench`` / ``make bench``: run the benchmark, print a summary,
write docs/BENCHMARKS.md and bench/results/latest.json.

Exit code 1 if the precision gates fail: any benign real domain, hard
negative or benign message flagged LIKELY or above.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from bench.harness import run
from lureradar import __version__
from lureradar.util.defang import defang

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "BENCHMARKS.md"
RESULTS = ROOT / "bench" / "results" / "latest.json"


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def render(r: dict[str, Any]) -> str:
    c = r["corpus"]
    off, scoped = r["offline"], r["offline_in_scope"]
    families = sum(1 for p in r["patterns"].values() if p["label"] == "lure")
    lines = [
        "# Benchmarks",
        "",
        "<!-- Generated by `make bench` (python -m bench). Do not edit by hand. -->",
        "",
        f"LureRadar {__version__} · seed {r['generated_with']['seed']} · reference time "
        f"{r['generated_with']['now']} · reproduce with `make bench`.",
        "",
        "## Headline",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| False-positive rate at LIKELY+, {c['benign_real_domains']} real benign domains | "
        f"**{pct(r['benign_fpr_likely'])}** (without allowlists: {pct(r['benign_fpr_likely_without_allowlists'])}) |",
        f"| False-positive rate at SUSPICIOUS+, same corpus | {pct(r['benign_fpr_suspicious'])} "
        f"(without allowlists: {pct(r['benign_fpr_suspicious_without_allowlists'])}) |",
        f"| Hard negatives ({c['benign_hard_negatives']} keyword-bearing fan/news names) flagged LIKELY+ / SUSPICIOUS+ | "
        f"{pct(r['hard_negative_fpr_likely'])} / {pct(r['hard_negative_fpr_suspicious'])} |",
        f"| Benign article URLs ({c['benign_article_urls']}) flagged SUSPICIOUS+ | {pct(r['article_url_fpr_suspicious'])} |",
        f"| Recall on in-scope synthetic lures, offline only: LIKELY+ / SUSPICIOUS+ | "
        f"{pct(scoped['likely']['recall'])} / {pct(scoped['suspicious']['recall'])} |",
        f"| Same lures when newly registered (< 3 days, as the live pipeline sees CT candidates): LIKELY+ / SUSPICIOUS+ | "
        f"{pct(r['newly_registered_lures']['likely_plus'])} / {pct(r['newly_registered_lures']['suspicious_plus'])} |",
        f"| Text lures ({c['text_messages']} synthetic messages): precision / recall at LIKELY+ | "
        f"{pct(r['text']['likely']['precision'])} / {pct(r['text']['likely']['recall'])} |",
        f"| Text: recall at SUSPICIOUS+, benign messages flagged | {pct(r['text']['suspicious']['recall'])}, "
        f"{pct(r['text']['likely']['fpr'])} |",
        "",
        "**How to read this.** LureRadar is precision-first: offline, lexical evidence alone",
        "rarely reaches LIKELY, by design (keyword + intent is CLEAR, a fake-platform claim",
        "is SUSPICIOUS, LIKELY needs a further independent signal such as brand",
        "impersonation). Blocklists publish LIKELY+ only. In production the pipeline adds",
        "live signals (registration age, certificate freshness, page content, external",
        "reputation), which is what moves real lures to LIKELY, as the newly-registered",
        "row shows. The synthetic lures were written by the same maintainers who wrote the",
        "detectors, so recall on covered patterns is optimistic. Precision on the real",
        "benign corpus is the number to trust.",
        "",
        "## Corpora",
        "",
        "| Corpus | Size | How it was built |",
        "|---|---|---|",
        f"| Real benign domains | {c['benign_real_domains']} | `bench/corpora/benign_domains.txt`: hand-curated, long-established sites (game press, studios, stores, wikis, fan databases, platforms, tools, news, telecoms, education, government, finance). No ranking snapshot could be downloaded from the build sandbox. |",
        f"| Hard negatives | {c['benign_hard_negatives']} | `bench/corpora/benign_hard_negatives.txt`: synthetic `.test` names a legitimate fan or news site could use (contain campaign keywords, no lure offer). |",
        f'| Benign article URLs | {c["benign_article_urls"]} | `bench/corpora/benign_urls.txt`: real outlet domains with synthetic GTA VI paths, including "PC download" questions. |',
        f"| Synthetic lures | {c['synthetic_lures']} ({c['synthetic_lures_in_scope']} in scope) | `bench/generators.py`: seeded generators across {families} pattern families, generated in memory, never resolved or committed. |",
        f"| Synthetic messages | {c['text_messages']} | `bench/text_generators.py`: template-generated lure and benign messages, distinct from the unit-test corpus. |",
        "",
        "Public, redistributable real-world lure samples with a verifiable licence were",
        "not available from the build environment, so none are included (rather than",
        "including unverified ones).",
        "",
        "## Recall by pattern (offline)",
        "",
        "| Pattern | n | SUSPICIOUS+ | LIKELY+ | In scope | Example (defanged, TLD shown as .example) |",
        "|---|---|---|---|---|---|",
    ]
    for name, p in r["patterns"].items():
        if p["label"] != "lure":
            continue
        ex = p["example"]
        host = ex.split("://", 1)[-1].split("/", 1)[0]
        shown = defang(ex.replace(host, host.rsplit(".", 1)[0] + ".example"))
        lines.append(
            f"| `{name}` | {p['n']} | {pct(p['suspicious_plus'])} | {pct(p['likely_plus'])} | "
            f"{'yes' if p['in_scope'] else 'no (blind spot)'} | `{shown}` |"
        )
    conf = r["confusion_offline"]
    tconf = r["text"]["confusion"]
    lines += [
        "",
        "## Confusion matrices (rows: label, columns: predicted tier)",
        "",
        "Domains and URLs, offline:",
        "",
        "| Label | CLEAR | SUSPICIOUS | LIKELY | CONFIRMED |",
        "|---|---|---|---|---|",
        *[
            f"| {lab} | {row['clear']} | {row['suspicious']} | {row['likely']} | {row['confirmed']} |"
            for lab, row in conf.items()
        ],
        "",
        "Messages:",
        "",
        "| Label | CLEAR | SUSPICIOUS | LIKELY | CONFIRMED |",
        "|---|---|---|---|---|",
        *[
            f"| {lab} | {row['clear']} | {row['suspicious']} | {row['likely']} | {row['confirmed']} |"
            for lab, row in tconf.items()
        ],
        "",
        "Domain metrics at each threshold (all lures, including blind spots):",
        "",
        "| Threshold | Precision | Recall | F1 | FPR |",
        "|---|---|---|---|---|",
        f"| LIKELY+ | {pct(off['likely']['precision'])} | {pct(off['likely']['recall'])} | {off['likely']['f1']:.3f} | {pct(off['likely']['fpr'])} |",
        f"| SUSPICIOUS+ | {pct(off['suspicious']['precision'])} | {pct(off['suspicious']['recall'])} | {off['suspicious']['f1']:.3f} | {pct(off['suspicious']['fpr'])} |",
    ]
    cal = r["calibration"]
    lines += [
        "",
        "## Calibration",
        "",
        "Weights are frozen in `src/lureradar/scoring/weights.py` (the indicative weights of",
        "the design brief). The benchmark measures them rather than fitting them to our own",
        "synthetic generator, which would overfit.",
        "",
        f"- Highest score of any real benign domain with allowlists **off**: **{cal['max_benign_score_without_allowlists']}**.",
        f"- Lowest threshold with zero benign false positives: {cal['lowest_zero_fpr_threshold']}.",
        f"- Margin below the LIKELY threshold (70): **{cal['likely_threshold_margin']} points**.",
        "",
        "| Score bucket | Real benign (no allowlists) | In-scope lures |",
        "|---|---|---|",
        *[
            f"| {b} | {cal['benign_histogram'][b]} | {cal['lure_histogram'][b]} |"
            for b in cal["benign_histogram"]
        ],
        "",
        "## Known blind spots",
        "",
        "- **No campaign keyword** (`free-games-download.example`): out of scope by design;",
        "  LureRadar targets launch campaigns, not generic piracy.",
        "- **Keywords not in the pack** (`leonida-pc-download.example`, setting or character",
        "  names): add them to `packs/gta6/keywords.yaml` when campaigns adopt them.",
        "- **Path-only lures on neutral hosts** (`files-cdn.example/gta6/pc-download/setup.exe`):",
        "  path signals are half-weight, so these stay CLEAR offline; `--live` content",
        "  analysis is what catches them.",
        "- **Brand-only phishing** (`take2-claim.example`) without a campaign keyword is CLEAR",
        "  offline unless it is a typosquat or uses a confusable IDN.",
        "- **Typosquats of brand labels** score 25 offline (CLEAR) and need a second signal,",
        "  for example a recent registration.",
        "",
        "## Bugs the benchmark found (fixed before release)",
        "",
        '- Multi-word platform terms shorter than 8 compact characters ("Switch 2") never',
        '  matched, so "GTA VI Switch 2 free download" messages scored CLEAR. Fixed and',
        "  covered by `test_multiword_platform_terms_match_in_text_and_hosts`.",
        '- A brand token that is also an intent ("steam") was counted twice, pushing the',
        "  hard negative `gta6-steam-deck-rumors.test` to SUSPICIOUS. Fixed.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "make bench",
        "```",
        "",
        "The command prints the summary, rewrites this file and `bench/results/latest.json`,",
        "and exits non-zero if any benign real domain, hard negative or benign message is",
        "flagged LIKELY or above. CI runs it on every push.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m bench")
    ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--json-out", type=Path, default=None, help="also write results JSON here")
    ap.add_argument("--no-write", action="store_true", help="do not rewrite docs/results")
    args = ap.parse_args(argv)
    r = run(seed=args.seed)
    text = json.dumps(r, indent=2, sort_keys=True) + "\n"
    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(text, encoding="utf-8")
    if not args.no_write:
        RESULTS.parent.mkdir(parents=True, exist_ok=True)
        RESULTS.write_text(text, encoding="utf-8")
        DOC.write_text(render(r), encoding="utf-8")
    scoped = r["offline_in_scope"]
    print(
        f"benign real domains: {r['corpus']['benign_real_domains']}  FPR@LIKELY+ "
        f"{pct(r['benign_fpr_likely'])} (no allowlists {pct(r['benign_fpr_likely_without_allowlists'])})"
    )
    print(
        f"hard negatives FPR@LIKELY+ {pct(r['hard_negative_fpr_likely'])}  "
        f"@SUSPICIOUS+ {pct(r['hard_negative_fpr_suspicious'])}"
    )
    print(
        f"in-scope lures recall offline: LIKELY+ {pct(scoped['likely']['recall'])}  "
        f"SUSPICIOUS+ {pct(scoped['suspicious']['recall'])}"
    )
    print(
        f"newly registered lures: LIKELY+ {pct(r['newly_registered_lures']['likely_plus'])}  "
        f"SUSPICIOUS+ {pct(r['newly_registered_lures']['suspicious_plus'])}"
    )
    t = r["text"]
    print(
        f"text: precision {pct(t['likely']['precision'])} recall {pct(t['likely']['recall'])} "
        f"@LIKELY+, recall {pct(t['suspicious']['recall'])} @SUSPICIOUS+"
    )
    print("confusion (domains):", json.dumps(r["confusion_offline"]))
    gates = [
        ("benign real domains at LIKELY+", r["benign_fpr_likely"] == 0),
        (
            "benign real domains at LIKELY+ without allowlists",
            r["benign_fpr_likely_without_allowlists"] == 0,
        ),
        ("hard negatives at LIKELY+", r["hard_negative_fpr_likely"] == 0),
        ("benign messages at LIKELY+", t["likely"]["fp"] == 0),
    ]
    failed = [name for name, ok in gates if not ok]
    for name in failed:
        print(f"GATE FAILED: {name}", file=sys.stderr)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
