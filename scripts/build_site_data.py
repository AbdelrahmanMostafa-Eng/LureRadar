def parity_cases() -> list[dict[str, Any]]:
    import yaml

    from lureradar.errors import LureRadarError
    from lureradar.scoring.engine import Engine

    engine = Engine(pack_ids=["gta6"], now=DEMO_NOW)
    messages = yaml.safe_load((FIXTURES / "text" / "messages.yaml").read_text("utf-8"))
    texts = [m["text"] for m in messages["lure"]] + [m["text"] for m in messages["benign"]]
    cases = []
    for target in [*PARITY_TARGETS, *texts]:
        try:
            v = engine.check(target)
        except LureRadarError as exc:
            cases.append({"input": target, "error": str(exc)})
            continue
        cases.append(
            {
                "input": target,
                "kind": v.kind.value,
                "score": v.score,
                "tier": v.tier.value,
                "signals": sorted({s.id for s in v.signals}),
                "host": v.host,
                "registrable": v.registrable_domain,
            }
        )
    return cases


