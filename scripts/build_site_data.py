def psl_rules() -> dict[str, list[str]]:
    """PSL rules in ASCII form; ``private`` holds private-section rules (``*.x`` / ``!x`` kept)."""
    import idna
    import tldextract

    ex = tldextract.TLDExtract(
        suffix_list_urls=(), cache_dir=None, include_psl_private_domains=True
    )
    extractor = ex._get_tld_extractor()
    rules: set[str] = set()
    wildcards: set[str] = set()
    exceptions: set[str] = set()
    private: set[str] = set()
    private_raw = set(extractor.private_tlds)

    def ascii_rule(rule: str) -> str | None:
        labels = []
        for label in rule.split("."):
            if label == "*" or label.isascii():
                labels.append(label.lower())
                continue
            try:
                labels.append(idna.encode(label, uts46=True).decode())
            except idna.IDNAError:
                return None
        return ".".join(labels)

    for raw in set(extractor.public_tlds) | set(extractor.private_tlds):
        rule = ascii_rule(raw.lstrip("!"))
        if rule is None:
            continue
        if raw in private_raw:
            private.add(("!" if raw.startswith("!") else "") + rule)
        if raw.startswith("!"):
            exceptions.add(rule)
        elif rule.startswith("*."):
            wildcards.add(rule[2:])
        else:
            rules.add(rule)
    return {
        "rules": sorted(rules),
        "wildcards": sorted(wildcards),
        "exceptions": sorted(exceptions),
        "private": sorted(private),
    }


def skeleton_map() -> dict[str, str]:
    """Exact export of the Python skeleton for the Unicode ranges lures use."""
    from lureradar.detectors.homoglyph import _skeleton_char

    ranges = [
        (0x00C0, 0x024F), (0x0250, 0x02AF), (0x0370, 0x03FF), (0x0400, 0x052F),
        (0x13A0, 0x13FF), (0x1D00, 0x1DBF), (0x1E00, 0x1EFF), (0x2100, 0x218F),
        (0x2460, 0x24FF), (0xA720, 0xA7FF), (0xFF00, 0xFFEF), (0x1D400, 0x1D7FF),
    ]  # fmt: skip
    out: dict[str, str] = {}
    for lo, hi in ranges:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            if unicodedata.category(ch).startswith("C"):
                continue
            sk = _skeleton_char(ch)
            if sk != ch and sk.isascii():
                out[ch] = sk
    return out


def build_rules() -> dict[str, Any]:
    import yaml

    from lureradar import __version__
    from lureradar.detectors.base import FILLER_WORDS, build_indexes, compact
    from lureradar.detectors.intent import SELF_ACQUIRING
    from lureradar.detectors.typosquat import _LOOKALIKES
    from lureradar.packs.loader import base_allowlist, load_packs
    from lureradar.scoring import tiers, weights
    from lureradar.textlure import patterns as p
    from lureradar.textlure.analyzer import _brand_regex
    from lureradar.util.domains import _RESERVED_TLDS, _shared_host_suffixes, split_host

    packs = load_packs()
    indexes = build_indexes(packs)
    data_dir = ROOT / "src" / "lureradar" / "data"
    abused = yaml.safe_load((data_dir / "abused_tlds.yaml").read_text("utf-8"))
    shorteners = yaml.safe_load((data_dir / "shorteners.yaml").read_text("utf-8"))
    pack_rules = []
    for idx in indexes:
        pack = idx.pack
        facts = pack.facts
        fact_notes: dict[str, str] = {}
        if facts:
            for name, plat in facts.platforms.items():
                fact = facts.fact(plat.fact) if plat.fact else None
                fact_notes[name] = (
                    f" (fact {fact.id}, as of {fact.as_of.isoformat()})"
                    if fact
                    else f" (facts as of {facts.as_of.isoformat()})"
                )
        pc_fact = facts.fact("pc_release") if facts else None
        pack_rules.append(
            {
                "id": pack.id,
                "name": pack.name,
                "subject": pack.subject_label,
                "keywords": [
                    {
                        "term": kp.term,
                        "pattern": kp.regex.pattern,
                        "needsRightBoundary": kp.needs_right_boundary,
                    }
                    for kp in idx.keywords
                ],
                "keywordsCompact": [compact(k) for k in pack.keywords],
                "intents": sorted(idx.intents),
                "acquisition": sorted(idx.acquisition),
                "platformTerms": sorted(idx.platform_terms),
                "unreleased": {k: sorted(v) for k, v in idx.unreleased.items()},
                "platformLabels": {
                    k: pack.platform_label(k) for k in (facts.platforms if facts else {})
                },
                "factNotes": fact_notes,
                "brandTokens": idx.brand_tokens,
                "brands": [
                    {
                        "name": b.name,
                        "label": b.label,
                        "aliases": [compact(a) for a in b.aliases],
                        "official": b.official,
                        "officialLabels": [split_host(d)[1] for d in b.official],
                    }
                    for b in pack.brands
                ],
                "officialDomains": sorted(idx.official_domains),
                "vocabulary": sorted(idx.vocabulary),
                "multiword": sorted(getattr(idx, "multiword", ())),
                "maxWord": idx.max_word,
                "outlets": pack.allowlist.outlets,
                "platforms": pack.allowlist.platforms,
                "releaseStorefronts": pack.release_storefronts,
                "factsAsOf": facts.as_of.isoformat() if facts else None,
                "pcRelease": {
                    "status": pc_fact.status,
                    "claim": " ".join(pc_fact.claim.split()),
                    "as_of": pc_fact.as_of.isoformat(),
                    "sources": [str(s.url) for s in pc_fact.sources],
                }
                if pc_fact
                else None,
            }
        )
    base = base_allowlist()
    brand_rx = _brand_regex(indexes)
    text_patterns = {
        name: getattr(p, name).pattern
        for name in (
            "FREE_OFFER", "OFF_PLATFORM", "PAYMENT", "URGENCY", "DISABLE_SECURITY",
            "EXECUTABLE", "ARCHIVE_PASSWORD", "TOO_GOOD", "CHEAP_PRICE", "SURVEY",
            "ACCOUNT_THREAT", "WARNING",
        )
    }  # fmt: skip
    return {
        "version": __version__,
        "generatedAt": datetime.now(UTC).isoformat(timespec="seconds"),
        "packs": pack_rules,
        "baseOutlets": base.outlets,
        "basePlatforms": base.platforms,
        "abusedTlds": sorted(abused["tlds"]),
        "shorteners": sorted(shorteners["domains"]),
        "sharedHosts": list(_shared_host_suffixes()),
        "reservedTlds": sorted(_RESERVED_TLDS),
        "selfAcquiring": sorted(SELF_ACQUIRING),
        "filler": sorted(FILLER_WORDS),
        "lookalikes": [list(x) for x in _LOOKALIKES],
        "skeleton": skeleton_map(),
        "psl": psl_rules(),
        "weights": {
            k: getattr(weights, k)
            for k in dir(weights)
            if k.isupper() and isinstance(getattr(weights, k), int)
        },
        "tiers": {
            "suspicious": tiers.SUSPICIOUS_AT,
            "likely": tiers.LIKELY_AT,
            "confirmed": tiers.CONFIRMED_AT,
        },
        "text": {
            "patterns": text_patterns,
            "brandPattern": brand_rx.pattern if brand_rx else None,
            "reassuranceBefore": p._REASSURANCE_BEFORE.pattern,
            "reassuranceAfter": p._REASSURANCE_AFTER.pattern,
        },
    }


