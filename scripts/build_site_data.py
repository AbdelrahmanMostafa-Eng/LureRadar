"""Generate the data the static site is built from.

    uv run python scripts/build_site_data.py [--feeds DIR]

Writes:
* ``web/src/data/generated/``: latest.json, all.json, stats.json, pc-watch.json,
  meta.json, packs.json, signals.json, parity.json, methodology.json (if bench
  results exist), docs.json;
* ``web/public/data/rules.json``: everything the client-side checker needs;
* ``web/public/feeds/``: feed copies for local preview (CI copies real feeds
  into ``dist/feeds`` after the build);
* ``web/public/og/``: per-page Open Graph images (via scripts/gen_og.py).

With ``--feeds DIR`` containing published feeds, real data is used. Otherwise
DEMO data is generated by running the pipeline on the recorded fixtures
(synthetic, reserved ``.test`` domains) and the site labels it as such.
"""

