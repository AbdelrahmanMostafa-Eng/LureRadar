def packs_summary() -> list[dict[str, Any]]:
    from lureradar.packs.loader import load_packs

    out = []
    for pack in load_packs():
        facts = pack.facts
        out.append(
            {
                "id": pack.id,
                "name": pack.name,
                "subject": pack.subject_label,
                "version": pack.version,
                "as_of": pack.as_of.isoformat(),
                "description": " ".join(pack.description.split()),
                "keywords": pack.keywords,
                "intents": pack.intents,
                "brands": [{"name": b.label, "official": b.official} for b in pack.brands],
                "allowlist_outlets": len(pack.allowlist.outlets),
                "allowlist_platforms": len(pack.allowlist.platforms),
                "platforms": {
                    k: {
                        "label": pack.platform_label(k),
                        "status": facts.effective_status(k),
                    }
                    for k in facts.platforms
                }
                if facts
                else {},
                "facts": [
                    {
                        "id": f.id,
                        "claim": " ".join(f.claim.split()),
                        "status": f.status,
                        "as_of": f.as_of.isoformat(),
                        "sources": [
                            {"url": str(s.url), "title": s.title, "publisher": s.publisher}
                            for s in f.sources
                        ],
                    }
                    for f in (facts.facts if facts else [])
                ],
            }
        )
    return out


def signals_doc() -> list[dict[str, str]]:
    from lureradar.scoring.explain import SIGNAL_DOCS

    return [
        {"id": k, "title": d.title, "weight": d.weight, "description": d.description}
        for k, d in SIGNAL_DOCS.items()
    ]


def docs_index() -> list[dict[str, str]]:
    docs = ROOT / "docs"
    out = []
    for path in sorted(docs.glob("*.md")) if docs.is_dir() else []:
        text = path.read_text("utf-8")
        title = next(
            (ln.lstrip("# ").strip() for ln in text.splitlines() if ln.startswith("# ")), path.stem
        )
        out.append({"slug": path.stem.lower().replace("_", "-"), "file": path.name, "title": title})
    return out


def methodology() -> dict[str, Any] | None:
    for cand in (ROOT / "bench" / "results" / "latest.json", ROOT / "build" / "bench.json"):
        if cand.is_file():
            return json.loads(cand.read_text("utf-8"))
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--feeds", type=Path, help="directory with published feeds")
    parser.add_argument("--no-og", action="store_true", help="skip Open Graph image rendering")
    args = parser.parse_args(argv)

    GEN.mkdir(parents=True, exist_ok=True)
    feeds_dir = args.feeds if args.feeds and (args.feeds / "latest.json").is_file() else None
    demo = feeds_dir is None
    with tempfile.TemporaryDirectory() as tmp:
        src = feeds_dir or Path(tmp) / "feeds"
        if demo:
            demo_feeds(src)
        for name in ("latest.json", "all.json", "stats.json"):
            shutil.copyfile(src / name, GEN / name)
        _dump(GEN / "pc-watch.json", pcwatch_state(args.feeds))
        preview = PUBLIC / "feeds"
        preview.mkdir(parents=True, exist_ok=True)
        for path in src.iterdir():
            if path.is_file():
                shutil.copyfile(path, preview / path.name)
        shutil.copyfile(GEN / "pc-watch.json", preview / "pc-watch.json")
        ensure_pcwatch_outputs(args.feeds, preview)
    # Serve the JSON Schemas at the URLs their "$id"s promise.
    schemas_out = PUBLIC / "schemas"
    schemas_out.mkdir(parents=True, exist_ok=True)
    for schema in (ROOT / "src" / "lureradar" / "schemas").glob("*.schema.json"):
        doc = json.loads(schema.read_text("utf-8"))
        published = doc.get("$id", "").rsplit("/", 1)[-1] or schema.name
        shutil.copyfile(schema, schemas_out / published)

    from lureradar import __version__
    from lureradar.config import REPO_URL, base_url

    stats = json.loads((GEN / "stats.json").read_text("utf-8"))
    meta = {
        "demo": demo,
        "demo_note": "Demo data: synthetic fixtures, reserved .test domains" if demo else "",
        "generated_at": stats.get("generated_at"),
        "version": __version__,
        "base_url": base_url(),
        "repo_url": REPO_URL,
        "built_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }
    _dump(GEN / "meta.json", meta)
    _dump(GEN / "packs.json", packs_summary())
    _dump(GEN / "signals.json", signals_doc())
    _dump(GEN / "docs.json", docs_index())
    _dump(GEN / "parity.json", parity_cases())
    bench = methodology()
    if bench is not None:
        _dump(GEN / "methodology.json", bench)
    elif (GEN / "methodology.json").exists():
        (GEN / "methodology.json").unlink()
    _dump(PUBLIC / "data" / "rules.json", build_rules())

    if not args.no_og:
        import gen_og

        pc = json.loads((GEN / "pc-watch.json").read_text("utf-8"))
        gen_og.render_site_cards(PUBLIC / "og", stats=stats, pcwatch=pc, demo=demo)
    print(f"site data written ({'DEMO fixtures' if demo else 'published feeds'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
