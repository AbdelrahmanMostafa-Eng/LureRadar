"""Guard the single-BASE_URL rule: the site hostname may only be configured in
src/lureradar/config.py and web/astro.config.mjs (plus files generated from
them and documented exceptions). Docs and README may link to the site."""

from __future__ import annotations

import re
import sys

from _common import ROOT, repo_files

# The canonical host, plus the retired GitHub Pages host so stale links are caught too.
SITE_HOST = re.compile(r"lureradar\.vercel\.app|abdelrahmanmostafa-eng\.github\.io", re.IGNORECASE)
CODE_EXT = {
    ".py",
    ".ts",
    ".tsx",
    ".js",
    ".mjs",
    ".astro",
    ".json",
    ".yml",
    ".yaml",
    ".toml",
    ".sh",
    ".html",
}
ALLOWED = {
    "src/lureradar/config.py",
    "web/astro.config.mjs",
    "pyproject.toml",  # [project.urls] metadata for PyPI
    "CITATION.cff",
    "extension/manifest.json",  # literal host permission, generated by scripts/sync_extension.py
    "extension/src/config.js",  # generated by scripts/sync_extension.py
    "scripts/check_hostnames.py",
    # generated from config.DEFAULT_BASE_URL by scripts/gen_schemas.py
    "src/lureradar/schemas/verdict.schema.json",
    "src/lureradar/schemas/feed.schema.json",
    "src/lureradar/schemas/pack.schema.json",
}


def main() -> int:
    bad = []
    for path in repo_files():
        rel = path.relative_to(ROOT).as_posix()
        if path.suffix not in CODE_EXT or rel in ALLOWED or "node_modules" in rel:
            continue
        if rel.startswith((".github/ISSUE_TEMPLATE/", "docs/", "packs/")):
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            if SITE_HOST.search(line):
                bad.append(f"{rel}:{lineno}")
    if bad:
        print("Hostname guard FAILED: derive URLs from BASE_URL instead of hardcoding:")
        print("\n".join(f"  {b}" for b in bad))
        return 1
    print("hostname guard: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
