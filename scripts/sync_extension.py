"""Generate extension/src/config.js and sync extension/manifest.json from
src/lureradar/config.py (the single BASE_URL source) and the package version.

    uv run python scripts/sync_extension.py          # write
    uv run python scripts/sync_extension.py --check  # CI: fail if out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from urllib.parse import urlsplit

from lureradar import __version__
from lureradar.config import DEFAULT_BASE_URL

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "extension" / "manifest.json"
CONFIG_JS = ROOT / "extension" / "src" / "config.js"


def render_config() -> str:
    return (
        "// GENERATED by scripts/sync_extension.py from src/lureradar/config.py. Do not edit.\n"
        f'export const SITE_URL = "{DEFAULT_BASE_URL}";\n'
        f'export const FEED_URL = "{DEFAULT_BASE_URL}feeds/latest.json";\n'
        f'export const FEED_URL_ALL = "{DEFAULT_BASE_URL}feeds/all.json";\n'
        f'export const VERSION = "{__version__}";\n'
    )


def synced_manifest() -> str:
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    origin = urlsplit(DEFAULT_BASE_URL)
    data["version"] = __version__
    data["host_permissions"] = [f"{origin.scheme}://{origin.netloc}/*"]
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    wanted = {CONFIG_JS: render_config(), MANIFEST: synced_manifest()}
    if "--check" in sys.argv:
        stale = [p for p, text in wanted.items() if p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run scripts/sync_extension.py")
        return 1 if stale else 0
    for p, text in wanted.items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
